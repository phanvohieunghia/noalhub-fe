/**
 * Generates two files from the locally installed @iconify-json sets:
 *
 *   src/icon-data.generated.ts — the icon data itself, inlined so nothing is
 *     fetched from api.iconify.design at runtime.
 *   src/icon-names.generated.ts — LUCIDE, a camelCase name -> "lucide:name" map
 *     covering every icon in the set, so editors autocomplete the whole set.
 *
 * Run `pnpm --filter @noalhub/ui gen:icons` after adding a prefix below.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, "../src");

/** Icon sets bundled in full. Each needs its `@iconify-json/<prefix>` devDep. */
const PREFIXES = ["lucide"];

const collections = [];
/** prefix -> { camelCaseKey: "prefix:icon-name" } */
const nameMaps = new Map();

for (const prefix of PREFIXES) {
  const data = await import(`@iconify-json/${prefix}/icons.json`, {
    with: { type: "json" },
  }).then((m) => m.default);

  collections.push(data);

  // Aliases are real, usable names too (lucide renames icons across releases).
  const names = [...Object.keys(data.icons), ...Object.keys(data.aliases ?? {})].sort();
  const map = {};
  for (const name of names) {
    const key = name.replace(/-(.)/g, (_, c) => c.toUpperCase());
    // A name starting with a digit ("1-circle") is not a valid identifier.
    map[/^[a-z]/.test(key) ? key : `_${key}`] = `${prefix}:${name}`;
  }
  nameMaps.set(prefix, map);
}

const banner = (what) =>
  `// GENERATED by scripts/generate-icon-data.mjs — do not edit by hand.\n` +
  `// Run \`pnpm --filter @noalhub/ui gen:icons\` to regenerate.\n` +
  `${what}\n`;

writeFileSync(
  resolve(src, "icon-data.generated.ts"),
  banner('import type { IconifyJSON } from "@iconify/react/offline";') +
    `\nexport const ICON_COLLECTIONS: IconifyJSON[] = ${JSON.stringify(collections)};\n`,
);

let namesFile = banner("");
for (const [prefix, map] of nameMaps) {
  const constName = prefix.toUpperCase().replace(/-/g, "_");
  const entries = Object.entries(map)
    .map(([key, value]) => `  ${key}: "${value}",`)
    .join("\n");
  namesFile +=
    `\n/** Every icon in the ${prefix} set, by camelCase name. */\n` +
    `export const ${constName} = {\n${entries}\n} as const;\n`;
}
writeFileSync(resolve(src, "icon-names.generated.ts"), namesFile);

const total = collections.reduce((n, c) => n + Object.keys(c.icons).length, 0);
const named = [...nameMaps.values()].reduce((n, m) => n + Object.keys(m).length, 0);
console.log(`Wrote ${total} icons and ${named} names (incl. aliases).`);
