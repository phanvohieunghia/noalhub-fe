/**
 * Generates src/icon-data.generated.ts from the locally installed
 * @iconify-json/lucide — the same set, and the same camelCase names, as the web
 * `LUCIDE` map in packages/ui.
 *
 * Unlike the web, only the icons listed below are bundled: the full set is
 * ~1,600 SVG bodies, which every app launch would parse for a handful of
 * glyphs. Add a name here and run `pnpm --filter @noalhub/ui-native gen:icons`.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const ICONS = [
  "arrow-left",
  "arrow-right",
  "check",
  "chevron-left",
  "chevron-right",
  "trophy",
  "x",
];

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../src/icon-data.generated.ts");

const set = await import("@iconify-json/lucide/icons.json", {
  with: { type: "json" },
}).then((m) => m.default);

const entries = ICONS.map((name) => {
  const icon = set.icons[name] ?? set.icons[set.aliases?.[name]?.parent];
  if (!icon) throw new Error(`lucide has no icon named "${name}"`);
  const key = name.replace(/-(.)/g, (_, c) => c.toUpperCase());
  const width = icon.width ?? set.width ?? 24;
  const height = icon.height ?? set.height ?? 24;
  return `  ${key}: { width: ${width}, height: ${height}, body: ${JSON.stringify(icon.body)} },`;
});

writeFileSync(
  out,
  `// GENERATED by scripts/generate-icon-data.mjs — do not edit by hand.
// Run \`pnpm --filter @noalhub/ui-native gen:icons\` to regenerate.

export type IconData = { width: number; height: number; body: string };

export const ICON_DATA = {
${entries.join("\n")}
} as const satisfies Record<string, IconData>;

export type IconName = keyof typeof ICON_DATA;
`,
);

console.log(`Wrote ${ICONS.length} icons to ${out}`);
